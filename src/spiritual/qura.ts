// قرعة الضمير: a lot in geomancy after the manuscript «القرعة في علم الرمل
// لاستخراج الضمير على الستة عشر شكلاً» (attributed in its text to Ja'far
// al-Sadiq; author unknown). Four handfuls of grains, each cast off two by
// two, leave one or two: four rows make a single figure, read from its
// section. The texts below follow the manuscript in plain wording; a planet
// is given only where the manuscript names one. AGPL-3.0-or-later.

