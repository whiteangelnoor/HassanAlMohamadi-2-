/** Four handfuls (counts of grains) give the four rows from the head down. */
export function castQura(counts: number[]): Figure {
  if (counts.length !== 4) {
    throw new Error('four handfuls are needed');
  }
  return counts.map(fromCount) as Figure;
}

export function quraEntry(f: Figure): QuraEntry {
  return QURA[f.join('')];
}

/** Four handfuls as a hand would take them, without counting. */
export function randomHandfuls(rand: () => number = Math.random): number[] {
  return Array.from({ length: 4 }, () => 7 + Math.floor(rand() * 30));
}
